import XCTest

final class SleepFlowTests: XCTestCase {
    func testOriginalDesignBilingualJournalAndNight() {
        let app = XCUIApplication()
        app.launchArguments = ["-AppleLanguages", "(en)", "-AppleLocale", "en_GB"]
        app.launch()
        XCTAssertTrue(app.tabBars.buttons["Settings"].waitForExistence(timeout: 10))
        app.tabBars.buttons["Settings"].tap()
        app.buttons["Light"].tap()
        capture("01-en-settings")
        app.tabBars.buttons["Alarms"].tap()
        XCTAssertTrue(app.buttons["Start the night"].waitForExistence(timeout: 5))
        capture("02-en-sunset")
        app.buttons["theme-toggle"].tap()
        capture("03-en-night")
        app.buttons["edit-alarm"].tap()
        XCTAssertTrue(app.buttons["Choose"].waitForExistence(timeout: 5))
        capture("04-en-editor")
        app.buttons["Choose"].tap()
        XCTAssertTrue(app.staticTexts["Forest at dawn"].waitForExistence(timeout: 5))
        XCTAssertTrue(app.buttons["import-song"].exists)
        capture("05-en-music")
        app.buttons["Done"].tap()
        app.buttons["Save"].tap()
        app.buttons["Start the night"].tap()
        let springboard = XCUIApplication(bundleIdentifier: "com.apple.springboard")
        let allow = springboard.buttons["Allow"]
        if allow.waitForExistence(timeout: 6) { allow.tap() }
        XCTAssertTrue(app.buttons["End"].waitForExistence(timeout: 12))
        capture("06-en-active-night")
        app.buttons["End"].tap()
        XCTAssertTrue(app.staticTexts["Sleep journal"].waitForExistence(timeout: 8))
        capture("07-en-journal")
        app.swipeUp()
        app.buttons["Energized"].tap()
        let notes = app.textViews["dream-notes"]
        if !notes.isHittable { app.swipeUp() }
        notes.tap(); notes.typeText("A calm start.")
        app.toolbars.buttons["Done"].tap()
        capture("08-en-notes")
        app.tabBars.buttons["Settings"].tap()
        app.buttons["Castellano"].tap()
        XCTAssertTrue(app.tabBars.buttons["Ajustes"].waitForExistence(timeout: 5))
        app.buttons["Claro"].tap()
        capture("09-es-settings")
        app.tabBars.buttons["Alarmas"].tap()
        XCTAssertTrue(app.buttons["Empezar la noche"].waitForExistence(timeout: 5))
        capture("10-es-sunset")
        app.buttons["edit-alarm"].tap()
        XCTAssertTrue(app.buttons["Escoger"].waitForExistence(timeout: 5))
        capture("11-es-editor")
        app.buttons["Guardar"].tap()
        app.tabBars.buttons["Diario"].tap()
        app.buttons["Hoy"].tap()
        capture("12-es-journal")
        app.buttons["full-calendar"].tap()
        XCTAssertTrue(app.navigationBars["Calendario"].waitForExistence(timeout: 5))
        capture("13-es-calendar")
        app.buttons["Cerrar"].tap()
        app.terminate(); app.launch()
        XCTAssertTrue(app.tabBars.buttons["Diario"].waitForExistence(timeout: 8))
        app.tabBars.buttons["Diario"].tap()
        app.swipeUp()
        XCTAssertEqual(app.textViews["dream-notes"].value as? String, "A calm start.")
        capture("14-es-persisted-notes")
    }
    private func capture(_ name: String) {
        let attachment = XCTAttachment(screenshot: XCUIScreen.main.screenshot())
        attachment.name = name; attachment.lifetime = .keepAlways; add(attachment)
    }
}
